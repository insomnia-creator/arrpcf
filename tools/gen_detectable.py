#!/usr/bin/env python3
"""Generate src/detectable_darwin.hpp from Discord's detectable apps database.

The upstream database is ~11 MB (all platforms, icons, SKUs, themes...). We only
need what process detection uses on macOS, which is a few kilobytes.

Usage:
    tools/gen_detectable.py                       # download from Discord
    tools/gen_detectable.py path/to/detectable.json
"""

from __future__ import annotations

import json
import pathlib
import sys
import urllib.request

URL = "https://discord.com/api/v9/applications/detectable"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "detectable_darwin.hpp"


def compact(entries: list[dict]) -> list[dict]:
    out = []
    for entry in entries:
        exes = []
        for exe in entry.get("executables") or []:
            if exe.get("os") != "darwin" or exe.get("is_launcher"):
                continue
            item = {"name": exe["name"], "os": "darwin"}
            if exe.get("arguments"):
                item["arguments"] = exe["arguments"]
            exes.append(item)
        if not exes:
            continue
        out.append({"id": entry["id"], "name": entry["name"], "executables": exes})
    return out


def main() -> int:
    if len(sys.argv) > 1:
        data = json.loads(pathlib.Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(URL) as response:
            data = json.load(response)

    reduced = compact(data)
    payload = json.dumps(reduced, separators=(",", ":"), ensure_ascii=False)
    delimiter = "ARRPCF_"
    if f"){delimiter}" in payload:  # cannot happen, but never emit a broken literal
        payload = payload.replace(f"){delimiter}", ")ARRPCF\\u005f")

    OUT.write_text(
        "// Generated by tools/gen_detectable.py. Do not edit by hand.\n"
        "// Source: Discord's detectable apps database, darwin entries only.\n"
        "#pragma once\n\n"
        f'static constexpr const char kDetectableDarwinJson[] = R"{delimiter}({payload}){delimiter}";\n'
    )
    print(f"wrote {OUT} ({len(reduced)} darwin apps, {len(payload)} bytes of JSON)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
